/*
 Schema for a two-variable example
 */

create schema example;

create table example.departments (
    id integer not null generated by default as identity,
    name text not null,
    parent_id integer,

    constraint departments_pkey primary key (id),
    constraint departments_parent_fkey foreign key (parent_id)
        references example.departments (id)
        on delete restrict on update restrict
);

create table example.employees (
    id integer not null generated by default as identity,
    department_id integer not null,
    first_name text not null,
    last_name text,
    position text not null,
    is_manager bool not null default false,

    constraint employees_pkey primary key (id),
    constraint employees_departments_fkey foreign key (department_id)
        references example.departments (id)
        on delete restrict on update restrict
);

create table example.documents (
    id integer not null generated by default as identity,
    author_id integer not null,
    title text not null,
    content text not null,

    constraint documents_pkey primary key (id),
    constraint documents_authors_fkey foreign key (author_id)
        references example.employees
        on delete restrict on update restrict
);

create table example.approval_participants (
    document_id integer not null,
    employee_id integer not null,
    approved bool default false,

    constraint approval_participants_pkey primary key (document_id, employee_id),
    constraint approval_documents_fkey foreign key (document_id)
        references example.documents (id)
        on delete restrict on update restrict,
    constraint approval_employees_fkey foreign key (employee_id)
        references example.employees (id)
        on delete restrict on update restrict
);
